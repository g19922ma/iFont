//   出し方のせいか」を常にそのまま読めるようにするため。48種は16通り全体を
//   1つの比較の網としてつなぐので、あとから全体の尺度化もできる。
//   音声の再生は同日に廃止した（質問が音声に触れないため。転写の進み方は
//   音声の識別実測から作った表 warp_tables に焼き込まれている）。
//
//   質問は強制二択のみ（順位づけ1問・途中感・快適さ7件法・「音声に合うか」は
//   いずれも 2026-08-30 に廃止。経緯は git 履歴と実験計画書に）。
//   進み方の表は本番の transfer_warp_comfort.json をそのまま読む。
