// =========================================================================
// 見え心地の評価（群C）設定ファイル
//   読むページ: experiment/transfer_comfort.html
//   読むコード: experiment/transfer_comfort.js
//   計画書:     project/実験計画書_転写検証.md（3章 RQ3・4.1・4.5）
//
//   ■ 群Cとは何か
//   「生成した4方式の文字アニメーションを、字幕として続けて見ていられるか」だけを
//   聞く独立の実験である。もとは群B（検証・視覚）の識別課題が全部終わったあとに
//   くっつけていたが、2026-08-21 に切り出して別の集団・別の掲載にした。理由は3つ。
//     (a) 90問以上の識別課題のあとでは疲れが混ざり、印象が課題の疲労に引きずられる
//     (b) 独立させれば「打ち切りなしで何度も繰り返し流す」提示にできる。
//         字幕は本来くりかえし流れるものなので、そのほうが実態に近い
//     (c) 群Bの負担が減る（識別課題だけで終われる）
//   掲載は検証フェーズ（群Atest・群B）と**並行**して行う。別の集団なので日程は延びない。
//
//   ■ このファイルの位置づけ
//   描画のパラメータ（キャンバスの大きさ・4方式の描き方・進み方の表）は
//   transfer_config.js（群A′・群Bと共用）を**読むだけ**で、こちらには持たない。
//   同じ絵を出さないと群Bの結果と並べて論じられないためである。
//   ここに置くのは「群Cだけの手続き」＝代表字・質問項目・繰り返しの間・保存先の分岐。
//
//   ■ 数値を触るときにここだけ見ればよい項目
//     1. chars              … 代表字（事前固定。結果を見てから選び直さない）
//     2. families           … 見せる4方式
//     3. loop               … 繰り返し再生の間合い
//     4. items / choice     … 7件法の3項目と、最後の4択1問
//     5. roster             … 名簿サーバの使い方（重複参加の照合）
// =========================================================================
window.TRANSFER_COMFORT_CONFIG = {
  // 設定の版。全レコードの config_version 列に入る（どの数値で取ったデータか分かる）。
  // prov = provisional（暫定）。A2 のあとに確定版へ差し替える。
  config_version: "comfort-prov-2026-08-21",

  // ---- 名簿（サーバ）での扱い ----------------------------------------------
  // 較正フェーズ（群Acal・群A′）とも検証フェーズ（群Atest・群B）とも重ならない
  // 独立集団にする。判定はサーバの参加者名簿でしかできないので、既定では
  // サーバに繋がらないときは課題を始めさせない。
  //
  // ⚠ **サーバ側（gas_transfer/code.gs）はまだ phase="comfort" を知らない。**
  //   知らないフェーズを聞かれると {"status":"error"} を返すので、この設定のままだと
  //   全員がお断り画面になる。掲載の前に次の2か所を足すこと（掲載前チェックリスト H-1）。
  //     (1) TRANSFER_PHASE_GROUPS に comfort: ["c"] を足す
  //     (2) transferStatus() の重複判定に次の2本を足す
  //         ・phase==="comfort" のとき、同じ人が calib か test の行にいれば断る
  //         ・phase==="test"    のとき、同じ人が comfort の行にいれば断る
  //           （群Cと検証フェーズは同時期に走るので、どちら向きにも塞ぐ必要がある）
  //   Firestore へ移したあとも、この2つの規則をそのまま移植する。
  roster: {
    phase: "comfort",
    group: "c",
    // false にすると、サーバが答えないときでも参加者IDのハッシュで連番を決めて
    // 続行する（重複の照合はできない。研究者の動作確認と、緊急時の逃げ道）。
    require_server: true,
  },

  // ---- 代表字（事前固定・結果を見てから選び直さない） ------------------------
  // ターゲット8字の中から、字の複雑さの両端になる2字を先に決め打ちしてある。
  //   あ … 画数が少なく単純 ／ ぱ … 半濁点があり画素が多い
  // 「効きそうな字だけ後から選んだ」と言われないための事前固定である。
  // 4字に増やすこともできる（例: ["あ","ぱ","し","ま"]）。そのぶん所要が倍になり、
  // 2字＝8本で約4分のところ、4字＝16本で約7分になる。
  chars: ["あ", "ぱ"],

  // 見せる方式。左から フェード・部分表示・ぼかし解除・ワイプ。
  families: ["fade", "reveal", "blur", "wipe"],

  // 評価に使う進み方。"proposed" は生成した表（transfer_warp.json）、"linear" は等速。
  // 表が無いときは等速で代用する（研究者の動作確認のとき。記録に fallback_used が残る）。
  condition: "proposed",

  // ---- 繰り返し再生 ---------------------------------------------------------
  // 群Cを切り出した理由のひとつが「字幕はくりかえし流れるものなので、
  // 1回こっきりで印象を聞くのは実態と違う」ことである。そこで評価しているあいだ、
  // 同じアニメを自動で流しつづける。
  //   hold_ms … 現れきった姿のまま止めておく時間
  //   gap_ms  … いったん消してから、次に流しはじめるまでの間
  //   max_plays … 自動での再生をここで打ち切る（回答が長引いたときの保険。0で無制限）
  loop: {
    enabled: true,
    hold_ms: 1200,
    gap_ms: 300,
    max_plays: 60,
  },
  // 「▶ もう一度みる」ボタンを出すか。押した回数は記録する。
  allow_replay: true,

  // ---- 各アニメのあとに聞く7件法3項目 ---------------------------------------
  // 1=まったくそう思わない 〜 7=とてもそう思う。
  // annoying（目障り・わずらわしい）だけ向きが逆なので、集計のときは反転すること。
  items: [
    { key: "readable", text: "この表示は継続して見やすい" },
    { key: "natural",  text: "変化が自然に感じる" },
    { key: "annoying", text: "目障り・わずらわしい" },
  ],
  scale_min_label: "まったくそう思わない",
  scale_max_label: "とてもそう思う",

  // ---- 最後の1問（4択） -----------------------------------------------------
  choice: {
    text: "字幕として普段使うなら、どの表示がよいですか。",
    labels: { fade: "だんだん濃くなる", reveal: "点が増えていく", blur: "ぼやけ→はっきり", wipe: "端から現れる" },
    // 選ぶ前に4方式の見本を並べて見直せるようにする。使う字（chars のどれか）。
    // 空にすると chars の1字目を使う。
    sample_char: "",
    // 見本を並べて出すか。false にすると文字だけの4択になる。
    show_samples: true,
    // 見本1つあたりの表示幅px（4つ横に並ぶので、狭い画面では自動で縮む）。
    sample_px: 120,
  },

  // ---- 記録 -----------------------------------------------------------------
  logging: {
    // 保存先URLと再送の設定は transfer_config.js の logging をそのまま使う
    // （同じスプレッドシート・同じデプロイ）。ここでは行き先のシートだけ決める。
    // "transfer_wellbeing" は群Bの見え心地用に作ってあるシートで、列はそのまま使える
    // （phase 列に "comfort"、group 列に "c" が入る）。**GAS 側の変更は要らない。**
    modality: "transfer_wellbeing",
  },
};
