// 見え心地の評価（群C）設定ファイル
//   読むページ: experiment/transfer_comfort.html
//   読むコード: experiment/transfer_comfort.js
//   計画書:     project/実験計画書_転写検証.md（3章 RQ3・4.1・4.5）
//
//   ■ 群Cとは何か
//   「生成した4方式の文字アニメーションを、字幕として続けて見ていられるか」だけを
//   聞く独立の実験である。もとは群B（検証・視覚）の識別課題が全部終わったあとに
//   くっつけていたが、2026-08-21 に切り出して別の集団・別の掲載にした。理由は3つ。
//     (a) 90問以上の識別課題のあとでは疲れが混ざり、印象が課題の疲労に引きずられる
//     (b) 独立させれば「打ち切りなしで何度も繰り返し流す」提示にできる。
//         字幕は本来くりかえし流れるものなので、そのほうが実態に近い
//     (c) 群Bの負担が減る（識別課題だけで終われる）
//   掲載は検証フェーズ（群Atest・群B）と**並行**して行う。別の集団なので日程は延びない。
//
//   ■ このファイルの位置づけ
//   描画のパラメータ（キャンバスの大きさ・4方式の描き方・進み方の表）は
//   transfer_config.js（群A′・群Bと共用）を**読むだけ**で、こちらには持たない。
//   同じ絵を出さないと群Bの結果と並べて論じられないためである。
//   ここに置くのは「群Cだけの手続き」＝使う字・提示のしかた・間合い・質問・保存先の分岐。
//
//   ■ 数値を触るときにここだけ見ればよい項目
//     1. single_char / sequence … 使う字（事前固定。結果を見てから選び直さない）
//     2. families               … 見せる4方式
//     3. presentations          … 提示のしかた3通り（1字／横に並べる／その場で入れ替える）
//     4. timing                 … 繰り返しの間合いと、字と字のあいだの空き
//     5. layout                 … 1字ぶんの大きさと字間
//     6. items / choice         … 7件法の3項目と、最後の2問
//     7. roster                 … 名簿サーバの使い方（重複参加の照合）
// =========================================================================
window.TRANSFER_COMFORT_CONFIG = {
  // 設定の版。全レコードの config_version 列に入る（どの数値で取ったデータか分かる）。
  // prov = provisional（暫定）。A2 のあとに確定版へ差し替える。
  config_version: "comfort-prov-2026-08-24",

  // ---- 名簿（サーバ）での扱い ----------------------------------------------
  // 較正フェーズ（群Acal・群A′）とも検証フェーズ（群Atest・群B）とも重ならない
  // 独立集団にする。判定はサーバの参加者名簿でしかできないので、既定では
  // サーバに繋がらないときは課題を始めさせない。
  //
  // ✓ **いまの保存基盤（Firestore）は phase="comfort" を知っている**
  //   （2026-08-21 に対応済み。transfer_config.js の phases.comfort = ["c"] と
  //   phase_blocks に入っていて、4方向すべての重複拒否が疎通確認で通っている。
  //   掲載前チェックリスト H-1／C-0）。**掲載前にサーバ側でやることは無い。**
  //
  //   重複拒否の向きは4本ある（群Cと検証フェーズは同時期に走るので、どちら向きにも塞ぐ）。
  //     ・comfort に来た人が calib にいれば断る ／ test にいれば断る
  //     ・test    に来た人が comfort にいれば断る
  //     ・calib は一番先に走るので断る相手がいない
  //
  // ⚠ GAS へ切り戻すときだけ注意。gas_transfer/code.gs にも同じ規則を書いてあるが、
  //   **まだデプロイしていない**。デプロイしないまま GAS を主にすると、
  //   require_server が true なので群Cの参加者が全員お断り画面になる
  //   （掲載前チェックリスト H-1b）。
  roster: {
    phase: "comfort",
    group: "c",
    // false にすると、サーバが答えないときでも参加者IDのハッシュで連番を決めて
    // 続行する（重複の照合はできない。研究者の動作確認と、緊急時の逃げ道）。
    require_server: true,
  },

  // ---- 代表字（事前固定・結果を見てから選び直さない） ------------------------
  // ターゲット8字の中から事前に決め打ちしてある。
  // 「効きそうな字だけ後から選んだ」と言われないための事前固定である。
  //
  // **字の種類は増やさない。** 群Cで比べたいのは「現れ方（4方式）」と
  // 「5文字続けるときの出し方（3通り）」であって、字の難しさではない。
  // 字を増やすと本数が倍々に増え、所要が伸びるだけで問いに答えられる量は増えない。
  //
  //   single_char … 1字だけ出す条件で使う字
  //   sequence    … 5字続けて出す条件で使う並び。
  //                 **意味のある語にしない**（言葉として読めてしまうと、
  //                 表示の見え心地ではなく語の読みやすさを答えられてしまう）。
  //                 あ・か・し・ま・ら は音の種類がばらけていて語を作らない。
  single_char: "あ",
  sequence: ["あ", "か", "し", "ま", "ら"],

  // ---- 提示のしかた（3通り） -------------------------------------------------
  //   single … 1字だけ（従来どおり）
  //   row5   … 5字を左から1字ずつ出し、**出た字はそのまま残す**（字幕的な見せ方）
  //   swap5  … 5字を**同じ位置で1字ずつ入れ替える**
  presentations: ["single", "row5", "swap5"],
  presentation_labels: {
    single: "1字だけ",
    row5: "5字を左から並べて、出た字は残す",
    swap5: "5字を同じ場所で入れ替える",
  },

  // 見せる方式。フェード・部分表示・ぼかし解除・ワイプ。
  families: ["fade", "reveal", "blur", "wipe"],

  // 評価に使う進み方。"proposed" は生成した表（transfer_warp.json）、"linear" は等速。
  // 表が無いときは等速で代用する（研究者の動作確認のとき。記録に progress_source が残る）。
  condition: "proposed",

  // ---- 繰り返し再生と、5字続けるときの間合い ---------------------------------
  // 群Cを切り出した理由のひとつが「字幕はくりかえし流れるものなので、
  // 1回こっきりで印象を聞くのは実態と違う」ことである。そこで評価しているあいだ、
  // 同じアニメを自動で流しつづける。
  //
  // ■ この条件で測りたいこと・測りたくないこと
  //   測りたいのは「字幕として続けて見ていられるか」だけである。
  //   **前後の字がお互いの見え方に干渉する現象（視覚的マスキング）は測らない。**
  //   それは連続提示そのものを扱う次の実験の領域なので、ここでは
  //   **干渉が起きない十分な間隔を空けたうえで**、見え心地だけを聞く。
  //
  // ■ inter_char_gap_ms = 300 の根拠
  //   視覚的マスキング（先に出た刺激と後から出た刺激が互いの処理を邪魔する現象）は、
  //   2つの刺激の**開始どうしの間隔（SOA）が0〜200ミリ秒**の範囲で起きるとされる。
  //   文字の識別に対する抑制は約60〜120ミリ秒で最も強く、120ミリ秒あたりで消える
  //   （Enns & Di Lollo のレビュー、経頭蓋磁気刺激による文字識別の抑制の研究など）。
  //   アニメ本体が300ミリ秒なので、**現れきってから300ミリ秒空ける**と、
  //   字と字の開始の間隔は 300 + 300 = **約600ミリ秒**になる。
  //   これは干渉が起きる時間帯（200ミリ秒以下）の3倍離れている。
  //
  //   ⚠ 2026-08-24: アニメ本体の長さ（transfer_config.js の visual.base_anim_ms）を
  //   600→300ミリ秒に変えた（群Bの対照条件を公平にするため。あちらの注記を見ること）ので、
  //   字と字の開始の間隔は 900→600ミリ秒に縮んだ。それでも干渉の帯域（200ミリ秒以下）の
  //   3倍あるので、inter_char_gap_ms は 300 のまま据え置いた。余裕をもっと取りたければ
  //   ここを 600 にすれば元の900ミリ秒に戻る。機械チェック
  //   （experiment/tools/check_comfort_render.js）は「アニメ＋空き が400ミリ秒未満」を
  //   不合格にするので、ここを削るときは注意すること。
  //
  // ■ 読み上げの速さとの関係
  //   録音した自然音声の実測（experiment/transfer_audio_manifest.json の全長）では、
  //   かな1字の長さは**ターゲット8字で303〜419ミリ秒（平均347）**、
  //   全68かなでも250〜451ミリ秒だった。字と字の間隔600ミリ秒は、
  //   その**1.7倍ほどゆっくり**にあたる（900ミリ秒のときは2.6倍だった）。
  //   読みを5文字続ける速さを土台にしつつ、
  //   前後の字が影響し合わないところまで十分に間を空けた、という位置づけである。
  //
  // ■ 横並び（row5）の字間について
  //   横並びでは出た字が残るので、残った字と新しく出る字が**空間的に隣り合う**。
  //   これは時間のマスキングではなく、隣の字が邪魔をする現象（crowding・側方抑制）の
  //   領域にあたる。対処として**字と字のすき間を1文字分以上あける**
  //   （layout.gap_ratio を1.0以上にする）。
  //
  //   hold_ms … 全部現れきった姿のまま止めておく時間
  //   gap_ms  … いったん消してから、次に流しはじめるまでの間
  timing: {
    // 1字が現れきってから、次の字が現れはじめるまでの間（ミリ秒）。上の根拠を参照。
    inter_char_gap_ms: 300,
    // 1字だけの条件の間合い。
    single: { hold_ms: 1200, gap_ms: 300 },
    // 5字続ける条件の間合い（全部出そろってから消すまで／消してから次の周まで）。
    sequence: { hold_ms: 1500, gap_ms: 500 },
    // 自動での繰り返しをここで打ち切る（回答が長引いたときの保険。0で無制限）。
    max_cycles: 40,
  },

  // ---- 画面の並べ方 ---------------------------------------------------------
  // **3条件とも1字あたりの表示の大きさをそろえる。** 1字だけの条件を大きく出すと、
  // 「提示のしかたの違い」ではなく「字の大きさの違い」を答えられてしまうため、
  // 5字を横に並べたときの1字ぶんの幅を、3条件すべてで使う。
  layout: {
    // 字と字のすき間 ÷ 字の幅。1.0 で「1文字分あける」（crowding 対策。上の注記）。
    gap_ratio: 1.0,
    // 1字ぶんの表示幅の上限px（広い画面で大きくなりすぎないように）。
    max_char_px: 120,
  },

  // 「▶ もう一度みる」ボタンを出すか。押した回数は記録する。
  allow_replay: true,

  // ---- 各アニメのあとに聞く7件法3項目 ---------------------------------------
  // 1=まったくそう思わない 〜 7=とてもそう思う。
  // annoying（目障り・わずらわしい）だけ向きが逆なので、集計のときは反転すること。
  items: [
    { key: "readable", text: "この表示は継続して見やすい" },
    { key: "natural",  text: "変化が自然に感じる" },
    { key: "annoying", text: "目障り・わずらわしい" },
  ],
  scale_min_label: "まったくそう思わない",
  scale_max_label: "とてもそう思う",

  // ---- 最後の質問（2問に分ける） ---------------------------------------------
  // 聞きたいことが2つある——「どの**現れ方**（方式）がよいか」と
  // 「5文字続けるとき、どの**出し方**がよいか」。1問にまとめると、
  // 参加者がどちらについて答えたのか分からなくなるので、**別々の問いに分ける**。
  //
  // 2問目の見本は、1問目で選ばれた方式で出す。こうすると、参加者は
  // 「自分が good と思った現れ方で、横に並べるか入れ替えるか」を見くらべられる。
  choice: {
    // 1問目: 現れ方（4択）
    family: {
      text: "字幕として普段使うなら、どの<b>現れ方</b>がよいですか。",
      note: "4つの見本がくりかえし流れています。見くらべてから選んでください。",
      labels: { fade: "だんだん濃くなる", reveal: "点が増えていく", blur: "ぼやけ→はっきり", wipe: "端から現れる" },
      // 見本を並べて出すか。false にすると文字だけの4択になる。
      show_samples: true,
    },
    // 2問目: 5文字続けるときの出し方（3択）
    presentation: {
      text: "5文字続けて出すとき、どの<b>出し方</b>がよいですか。",
      note: "1問目で選んだ現れ方で、2つの見本を出しています。",
      labels: {
        row5: "左から並べて、出た字は残す",
        swap5: "同じ場所で1字ずつ入れ替える",
        either: "どちらでもよい・決められない",
      },
      // 見本を出す選択肢（either には見本が無い）。
      sample_options: ["row5", "swap5"],
      show_samples: true,
    },
  },

  // ---- 記録 -----------------------------------------------------------------
  logging: {
    // 保存先と再送の設定は transfer_config.js の backend / firestore / logging を
    // そのまま使う（**既定は Firestore**。GAS は切り戻し用の受け皿として残してある）。
    // ここで決めるのは行き先の入れ物だけ。
    // "transfer_wellbeing" は群Bの見え心地用に作ってあるコレクションで、
    // 列はそのまま使える（phase 列に "comfort"、group 列に "c" が入る）。
    //
    // 同じ入れ物に3種類の行が入るので、**record_kind 列で見分ける**
    // （transfer_comfort.js が付ける）。
    //   "clip"    … 1本ぶんの中間レコード（12行／人・保険。分析には使わない）
    //   "final"   … 1参加者1行の本記録（**分析はこれを読む**）
    //   "session" … 完走レコード（承認の照合はこの1行で済む）
    modality: "transfer_wellbeing",
  },
};
